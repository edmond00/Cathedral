/// <summary>
/// What an item is made of, as far as crafting cares. A crafting station works exactly one material
/// (<see cref="CraftingStationAttribute"/>): an item broken down there gives back that material and
/// nothing else, and everything made there is paid for in it.
///
/// <para>Three of them are <b>refined</b>: metal, cloth and leather are what ore, fibre and hide become
/// at a station whose recipes turn one into the other (the smelter's hearth, the loom, the tanning pit).
/// A recipe chain is never longer than that one step.</para>
///
/// <para>Deliberately not <see cref="ItemKind"/>. A kind is what a will can want — generous and
/// cross-cutting — and a material is what is left in the hand once the thing has been taken apart.
/// A tunic is a garment and is made of cloth; a knife is a tool and a blade and is made of iron and
/// wood.</para>
/// </summary>
public enum CraftMaterial
{
    Ore,
    Metal,
    Wood,
    Fibre,
    Cloth,
    Hide,
    Leather,
    Clay,
    Fat,
    Bone,
    Stone,
}

public static class CraftMaterials
{
    public static readonly CraftMaterial[] All = Enum.GetValues<CraftMaterial>();

    /// <summary>The materials that are what another one becomes at a station.</summary>
    public static bool IsRefined(this CraftMaterial m) => m is CraftMaterial.Metal or CraftMaterial.Cloth or CraftMaterial.Leather;

    /// <summary>The raw material a refined one is made from, or null for a raw material.</summary>
    public static CraftMaterial? RefinedFrom(this CraftMaterial m) => m switch
    {
        CraftMaterial.Metal   => CraftMaterial.Ore,
        CraftMaterial.Cloth   => CraftMaterial.Fibre,
        CraftMaterial.Leather => CraftMaterial.Hide,
        _                     => null,
    };

    /// <summary>Lower-case, for sentences and the menu ("metal", "cloth").</summary>
    public static string Label(this CraftMaterial m) => m.ToString().ToLowerInvariant();
}

/// <summary>
/// The material content of every item: which materials it holds (<see cref="Of"/>) and how many units
/// of each (<see cref="Units"/>, the same for every material it holds).
///
/// <para><b>Units come from the weight label</b>, not from a declaration: insignificant 1, light 2,
/// medium 4, heavy 8 — doubling at each step, so a nail still holds a unit of iron and a saddle does not
/// cost seven swords' worth of material. Flatter than the carrying scale (0/2/5/15) on purpose: a price
/// is worked out from the same units (<see cref="ItemPricing"/>), and on the carrying scale weight alone
/// priced every heavy thing above every precious one. Making a thing costs exactly what breaking it down
/// gives back, so the two directions can never disagree.</para>
///
/// <para>The table is keyed by <b>type</b>, never by name, like everything else that identifies content.
/// Only a consumable may be absent from it — a loaf, an apple. <c>--craft-audit</c> fails on anything
/// else that holds no material.</para>
/// </summary>
public static class ItemMaterials
{
    private static CraftMaterial[] M(params CraftMaterial[] m) => m;

    /// <summary>Units of material in one item of this weight.</summary>
    public static int Units(WeightClass weight) => weight switch
    {
        WeightClass.Insignificant => 1,
        WeightClass.Light         => 2,
        WeightClass.Medium        => 4,
        _                         => 8,
    };

    /// <summary>Units of each material <paramref name="item"/> holds.</summary>
    public static int Units(Item item) => Units(item.Weight);

    /// <summary>Every material <paramref name="item"/> holds; empty when it holds none.</summary>
    public static IReadOnlyList<CraftMaterial> Of(Item item) => Of(item.GetType());

    public static IReadOnlyList<CraftMaterial> Of(Type itemType)
        => Table.TryGetValue(itemType, out var m) ? m : Array.Empty<CraftMaterial>();

    public static bool Holds(Item item, CraftMaterial material) => Of(item).Contains(material);

